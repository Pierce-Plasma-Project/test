#!/usr/bin/env python3
"""An explicit counterexample to the Dixmier conjecture for A_3,
quantizing the Alpoge/Fable 5 Jacobian counterexample.

The Weyl algebra A_3 is generated by x1,x2,x3,d1,d2,d3 with relations
[di,xj] = delta_ij, [xi,xj] = [di,dj] = 0. Define

    X_i = F_i(x) (multiplication),      D_i = sum_k G[k][i] d_k,

where F is the counterexample map (det JF = -2) and G = (JF)^{-1} =
-adj(JF)/2, a matrix with POLYNOMIAL entries because det JF is a unit.

This script verifies, in exact symbolic arithmetic, every identity the
accompanying note (drafts/dixmier-note.md) relies on:

  (V1) JF * G = G * JF = I, and det JF = -2        (G is polynomial)
  (V2) sum_k G[k][i] * d(F_j)/d(x_k) = delta_ij     => [D_i, X_j] = delta_ij
  (V3) D_i(G[l][j]) - D_j(G[l][i]) = 0  (all i<j, l) => [D_i, D_j] = 0
       (second-order terms of the commutator cancel identically; the
        first-order coefficient is exactly this expression)
  (V4) chain rule: D_i(p(F)) = (dp/du_i)(F) on sample polynomials p —
       the engine of the non-surjectivity proof
  (V5) operator-level spot check: the commutators act as claimed on a
       batch of random polynomials.

Together with F(0,0,-1/4) = F(1,-3/2,13/2) (verified in verify.py), the
note's Lemma gives: the endomorphism X_i, D_i of A_3 is NOT surjective.
"""
import itertools
import random

import sympy as sp

x1, x2, x3 = sp.symbols("x1 x2 x3")
X = (x1, x2, x3)

F = (
    (1 + x1*x2)**3 * x3 + x2**2 * (1 + x1*x2) * (4 + 3*x1*x2),
    x2 + 3*x1 * (1 + x1*x2)**2 * x3 + 3*x1*x2**2 * (4 + 3*x1*x2),
    2*x1 - 3*x1**2*x2 - x1**3*x3,
)

JF = sp.Matrix(3, 3, lambda i, j: sp.diff(F[i], X[j]))
det = sp.expand(JF.det())
assert det == -2
G = (JF.adjugate() / det).applyfunc(sp.expand)   # polynomial inverse

# (V1)
assert (JF * G).applyfunc(sp.expand) == sp.eye(3)
assert (G * JF).applyfunc(sp.expand) == sp.eye(3)
print("(V1) JF * G = G * JF = I with det JF = -2, G polynomial: OK")

# (V2)  [D_i, X_j] = delta_ij
for i, j in itertools.product(range(3), repeat=2):
    val = sp.expand(sum(G[k, i] * sp.diff(F[j], X[k]) for k in range(3)))
    assert val == (1 if i == j else 0), (i, j, val)
print("(V2) [D_i, X_j] = delta_ij (9 polynomial identities): OK")


def D(i, f):
    """The operator D_i applied to a polynomial f."""
    return sp.expand(sum(G[k, i] * sp.diff(f, X[k]) for k in range(3)))


# (V3)  [D_i, D_j] = 0
for i, j in itertools.combinations(range(3), 2):
    for l in range(3):
        c = sp.expand(D(i, G[l, j]) - D(j, G[l, i]))
        assert c == 0, (i, j, l)
print("(V3) [D_i, D_j] = 0 (9 polynomial identities): OK")

# (V4)  chain rule D_i(p(F)) = (d p/d u_i)(F)
u1, u2, u3 = sp.symbols("u1 u2 u3")
U = (u1, u2, u3)
random.seed(7)
for trial in range(3):
    p = sum(random.randint(-3, 3) * u1**a * u2**b * u3**c
            for a in range(2) for b in range(2) for c in range(2))
    pF = p.subs(dict(zip(U, F)))
    for i in range(3):
        lhs = D(i, sp.expand(pF))
        rhs = sp.expand(sp.diff(p, U[i]).subs(dict(zip(U, F))))
        assert sp.expand(lhs - rhs) == 0, (trial, i)
print("(V4) chain rule D_i(p(F)) = (dp/du_i)(F) on sample p: OK")

# (V5) operator-level commutators on random polynomials
def Xop(i, f):
    return sp.expand(F[i] * f)

for trial in range(3):
    f = sum(random.randint(-2, 2) * x1**a * x2**b * x3**c
            for a in range(2) for b in range(2) for c in range(2))
    for i, j in itertools.product(range(3), repeat=2):
        comm1 = sp.expand(D(i, Xop(j, f)) - Xop(j, D(i, f)))
        assert sp.expand(comm1 - (f if i == j else 0)) == 0
        if i < j:
            comm2 = sp.expand(D(i, D(j, f)) - D(j, D(i, f)))
            assert comm2 == 0
print("(V5) commutator action on random polynomials: OK")

print()
print("All identities verified. The operators")
print("    X_i = F_i(x)*,   D_i = sum_k G[k][i] d/dx_k")
print("satisfy the defining relations of A_3 and generate a proper")
print("subalgebra (see drafts/dixmier-note.md, Lemma + the verified")
print("collision F(0,0,-1/4) = F(1,-3/2,13/2)):")
print("an explicit NON-SURJECTIVE endomorphism of the Weyl algebra A_3.")
print()
print("Explicit momentum coefficients G[k][i] (D_i = sum_k G[k][i] d_k):")
for i in range(3):
    for k in range(3):
        print(f"  G[{k+1}][{i+1}] = {sp.factor(G[k, i])}")
